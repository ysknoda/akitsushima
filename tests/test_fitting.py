@pytest.mark.parametrize("model_module", [
    "akitsushima.fitting.models.elm",
    "akitsushima.fitting.models.nn",
    "akitsushima.fitting.models.lightgbm_model",
])
def test_every_model_routes_its_split_through_the_grouped_helper(
        model_module, tmp_path, monkeypatch):
    """
    F17 regression, at the level of the callers.

    Fixing ``csv_io.structure_grouped_split`` achieves nothing for a model
    that still does its own row-wise shuffle -- and indeed ELM, NN and
    LightGBM each carried their own copy of that shuffle.  This asserts
    every model module actually imported the leak-free helper into its own
    namespace, which is what makes the monkeypatched spy below fire.
    """
    import importlib

    # OMP_NUM_THREADS must be pinned BEFORE lightgbm is first imported,
    # not just before LightGBMModel is constructed.  numba and lightgbm
    # each bring their own OpenMP runtime, and loading both unpinned in
    # one process aborts with SIGABRT (the F15 conflict documented for
    # this package).  The env var only takes effect while the OpenMP
    # runtime is still uninitialised, so setting it after
    # import_module() -- as this test originally did -- is too late.
    # The main dev environment hid this: earlier LightGBM tests in this
    # file already pin the variable and leave lightgbm in sys.modules,
    # so import_module() here was a cache hit.  A clean environment
    # (e.g. the pip_preparation install smoke test) imports it here for
    # the first time and aborts the whole pytest process.
    if model_module.endswith("lightgbm_model"):
        monkeypatch.setenv("OMP_NUM_THREADS", "1")

    mod = importlib.import_module(model_module)
    assert hasattr(mod, "structure_grouped_split"), (
        f"{model_module} must import structure_grouped_split; without it "
        f"the module still has its own row-wise split")

    # The spy must actually be reached when the model fits.
    calls = []
    real = mod.structure_grouped_split

    def spy(labels, **kw):
        calls.append(kw.get("caller", "?"))
        return real(labels, **kw)

    monkeypatch.setattr(mod, "structure_grouped_split", spy)

    csv_path = tmp_path / "train.csv"
    _multi_structure_mlip_csv(csv_path, n_structures=6, n_atoms=2)

    if model_module.endswith("elm"):
        m = mod.ELMModel(n_hidden=8, reg=1e-3, verbose=False, seed=0)
    elif model_module.endswith("nn"):
        pytest.importorskip("torch")
        m = mod.NNModel(hidden_layers=[4], epochs=1, batch_size=8,
                        verbose=False, seed=0)
    else:
        pytest.importorskip("lightgbm")
        pytest.importorskip("optuna")
        m = mod.LightGBMModel(optuna_trials=1, verbose=False, seed=0)

    m.fit_csv(str(csv_path), val_fraction=0.34)

    assert calls, (
        f"{model_module}'s fit() did not call structure_grouped_split -- "
        f"it is still splitting rows on its own")


def test_make_force_fn_engine_backend_honours_charges(small_cell_ok):
    """charges= must not be accepted and dropped.

    It is keyword-only and shared with the 'buckingham' backend, and the
    PotentialEngine branch used to ignore it silently.  Asking for an
    ionic crystal and getting a neutral one back is the largest silent
    error this function can make: for wurtzite ZnO it moves the energy
    from -19.7 to +3.1 eV/atom, bound to unbound.

    The two backends build the same Buckingham potential, so with the
    same charges they must return the same numbers.
    """
    from akitsushima.engine import BuckinghamPotential, PotentialEngine
    from akitsushima.fitting.force_fn import make_force_fn

    nacl = rocksalt_nacl_dict()
    pair = frozenset({"Na", "Cl"})
    buck = {pair: {"A": 1200.0, "rho": 0.32, "C": 25.0}}
    charges = {"Na": 1.0, "Cl": -1.0}
    r_cut = 4.0

    engine = PotentialEngine().add(
        BuckinghamPotential(buck, r_cut=r_cut,
                            allow_minimum_image_violation=True))
    fn_engine = make_force_fn(engine, charges=charges, r_cut=r_cut)
    fn_legacy = make_force_fn("buckingham", buck_params=buck,
                              charges=charges, r_cut=r_cut)

    args = (nacl["lattice"], nacl["positions"], nacl["atom_types"])
    e_eng, f_eng, s_eng = fn_engine(*args)
    e_leg, f_leg, s_leg = fn_legacy(*args)

    assert e_eng == pytest.approx(e_leg, rel=1e-12), (
        f"engine backend with charges= gave {e_eng:.6f} eV against the "
        f"'buckingham' backend's {e_leg:.6f} eV -- a gap this size is the "
        f"electrostatic energy going missing")
    assert np.allclose(f_eng, f_leg, atol=1e-12)
    assert np.allclose(s_eng, s_leg, atol=1e-12)

    # And the electrostatics must actually be present, or the test above
    # would pass on two equally neutral calculations.
    fn_neutral = make_force_fn(engine, r_cut=r_cut)
    e_neutral, _, _ = fn_neutral(*args)
    assert abs(e_eng - e_neutral) > 1.0, (
        f"test premise: the Coulomb term must be a large part of this "
        f"energy, but with and without charges differ by only "
        f"{abs(e_eng - e_neutral):.3e} eV")
