def _make_training_structures(engine, raw_structures, r_cut, charges=None,
                               ewald_alpha=None, coulomb_method="ewald",
                               name_prefix="s"):
    """Build fit_potential-format structure dicts with reference E/F/S taken
    directly from `engine` (+ optional Coulomb), i.e. data generated by a
    *known* ground-truth potential so a correct fit can drive the loss to
    (near) zero."""
    out = []
    for i, raw in enumerate(raw_structures):
        e, f, s = compute_all_general(
            raw["lattice"], raw["positions"], raw["atom_types"], engine,
            charges=charges, r_cut=r_cut, ewald_alpha=ewald_alpha,
            coulomb_method=coulomb_method)
        n = len(raw["positions"])
        out.append({
            "lattice": raw["lattice"],
            "positions": raw["positions"],
            "atom_types": raw["atom_types"],
            "natoms": n,
            "ref_energy": e / n,
            "ref_forces": f,
            "ref_stress": s,
            "volume": abs(np.linalg.det(raw["lattice"])),
            "name": f"{name_prefix}_{i}",
        })
    return out


def _perturbed_set(base_dict, n=3, magnitude=0.06):
    return [randomly_perturbed(base_dict, magnitude=magnitude, seed=i)
            for i in range(n)]


