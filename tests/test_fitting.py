def test_loss_huber_tempers_outlier_structure_relative_to_squared(small_cell_ok):
    """Fix C (Huber loss) regression: with one badly-off outlier
    structure and several well-behaved ones, Huber mode must give the
    outlier LESS influence over the total loss than plain squared mode
    (the whole point of a robust loss) -- and with a huge delta (never
    triggering the outlier branch), Huber mode must reproduce plain
    squared mode almost exactly (consistency / backward-compatibility
    check on the transform itself)."""
    al = fcc_al_dict()
    pair = frozenset({"Al"})
    true_lj = {pair: {"epsilon": 0.40, "sigma": 2.5}}
    engine_true = PotentialEngine()
    from akitsushima.engine import LennardJonesPotential
    engine_true.add(LennardJonesPotential(true_lj, r_cut=6.0, shift=True,
    allow_minimum_image_violation=True))

    good_structs = _make_training_structures(
        engine_true, _perturbed_set(al, n=3, magnitude=0.03), r_cut=6.0)
    # A deliberately-corrupted "outlier" reference energy (as if from a
    # non-converged DFT calculation), far outside the other structures'
    # residual scale.
    outlier = dict(good_structs[0])
    outlier["ref_energy"] = outlier["ref_energy"] + 50.0
    structs = good_structs + [outlier]

    wrong_lj = {pair: {"epsilon": 0.30, "sigma": 2.6}}
    param_set = LJParameterSet([pair], ["Al"], wrong_lj, r_cut=6.0, shift=True)
    weights = {"energy": 1.0, "forces": 1.0, "stress": 0.1}
    x = param_set.x0

    loss_squared = generic_loss_function(x, param_set, structs, weights,
                                         r_cut=6.0, ewald_alpha=None)

    weights_huber = dict(weights, huber_delta_energy=0.5,
                        huber_delta_forces=0.5, huber_delta_stress=0.5)
    loss_huber = generic_loss_function(x, param_set, structs, weights_huber,
                                       r_cut=6.0, ewald_alpha=None,
                                       loss_type="huber")
    assert loss_huber < loss_squared, (
        "Huber loss must temper the outlier structure's influence, "
        "giving a smaller total loss than plain squared error")

    weights_huber_huge = dict(weights, huber_delta_energy=1e6,
                              huber_delta_forces=1e6, huber_delta_stress=1e6)
    loss_huber_huge_delta = generic_loss_function(
        x, param_set, structs, weights_huber_huge,
        r_cut=6.0, ewald_alpha=None, loss_type="huber")
    assert loss_huber_huge_delta == pytest.approx(loss_squared, rel=1e-8), (
        "Huber loss with a delta far larger than any residual must "
        "reproduce plain squared-error loss (the r <= delta branch only)")


def test_fit_potential_reduces_loss_from_bad_initial_guess(tmp_path, small_cell_ok):
    al = fcc_al_dict()
    structs_raw = _perturbed_set(al)
    pair = frozenset({"Al"})
    true_lj = {pair: {"epsilon": 0.40, "sigma": 2.5}}
    engine_true = PotentialEngine()
    from akitsushima.engine import LennardJonesPotential
    engine_true.add(LennardJonesPotential(true_lj, r_cut=6.0, shift=True,
    allow_minimum_image_violation=True))
    structs = _make_training_structures(engine_true, structs_raw, r_cut=6.0)

    bad_lj = {pair: {"epsilon": 0.10, "sigma": 2.9}}
    param_set = LJParameterSet([pair], ["Al"], bad_lj, r_cut=6.0, shift=True)
    weights = {"energy": 1.0, "forces": 1.0, "stress": 0.1}

    initial_loss = generic_loss_function(param_set.x0, param_set, structs,
                                          weights, r_cut=6.0, ewald_alpha=None)
    result = fit_potential(param_set, structs, r_cut=6.0, weights=weights,
                            val_fraction=0.0, verbose=False,
                            output_dir=str(tmp_path))
    # This is a light integration smoke test of the optimiser plumbing, not
    # a convergence benchmark (only 3 structures, gradient-free L-BFGS-B) --
    # test_lj_loss_is_zero_at_true_parameters is the tight correctness check
    # on generic_loss_function/build_engine itself.
    assert result["loss"] < initial_loss * 0.9


