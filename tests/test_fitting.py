def _multi_structure_mlip_csv(path, n_structures=8, n_atoms=4, D=3, seed=0):
    """A CSV in this package's MLIP layout, where every structure emits
    1 E row + 3N F rows + 6 S rows -- all of them derived from the SAME
    atomic configuration, which is exactly why they must never be split
    across the train/validation boundary."""
    rng = np.random.default_rng(seed)
    lines = ["target,label,weight,feat0,feat1,feat2"]
    for _ in range(n_structures):
        for lab, count in (("E", 1), ("F", 3 * n_atoms), ("S", 6)):
            for _ in range(count):
                x = rng.normal(size=D)
                lines.append(f"{float(np.sum(x))},{lab},1.0,"
                             f"{x[0]},{x[1]},{x[2]}")
    path.write_text("\n".join(lines))


@pytest.mark.parametrize("val_seed", [0, 1, 2, 3, 4])
def test_structure_grouped_split_never_leaks_a_structure(val_seed):
    """
    F17 regression, at the level of the split itself.

    Every model's ``fit()`` used to shuffle CSV ROWS
    (``rng.permutation(N)``).  Because one structure contributes
    1 E + 3N F + 6 S rows that all describe the same configuration, a
    row-wise split lands rows of the same structure on both sides, so the
    "validation" score measures memorisation rather than generalisation --
    and for LightGBM it is precisely that leaked score Optuna minimises.
    Measured on this very fixture, 8/8 structures leaked at val_seed 0
    and 1.

    The invariant is unambiguous and needs no reference data: the
    intersection of the structure sets on the two sides must be EMPTY.
    """
    from akitsushima.fitting.models.csv_io import (
        infer_structure_ids,
        structure_grouped_split,
    )

    n_structures, n_atoms = 8, 4
    labels = np.array(
        (["E"] + ["F"] * (3 * n_atoms) + ["S"] * 6) * n_structures)
    sids = infer_structure_ids(labels)
    assert sids.max() + 1 == n_structures, "fixture sanity"

    idx_train, idx_val = structure_grouped_split(
        labels, val_fraction=0.25, val_seed=val_seed)

    assert idx_val.size > 0, "this fixture must be splittable"
    train_structs = set(sids[idx_train].tolist())
    val_structs = set(sids[idx_val].tolist())

    assert train_structs & val_structs == set(), (
        f"F17 regression: no structure may appear on both sides of the "
        f"split; leaked {sorted(train_structs & val_structs)}")
    assert train_structs | val_structs == set(range(n_structures)), (
        "every structure must land on exactly one side")
    # Every row of a structure must follow its structure.
    assert len(idx_train) + len(idx_val) == len(labels)


