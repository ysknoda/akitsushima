# Printed value -> value used.  Table III prints Al A = 0.134873.  The
# paper defines r_e as the equilibrium nearest-neighbour spacing, and every
# other fcc / bcc row satisfies a0 = sqrt(2) r_e (fcc) or 2 r_e / sqrt(3)
# (bcc) to 4e-6 relative with the engine; with 0.134873 fcc Al has no
# minimum near there at all (a0 3.44 A against 4.0502, E_coh 5.42 eV).
# With 0.314873 -- the value recalled from the parameter file of Zhou's
# LAMMPS generator (not re-read here, UNVERIFIED as a source) -- a0 =
# 4.05019 A = sqrt(2) r_e, E_coh 3.58 eV and B 75.9 GPa.  The self-
# consistency, not the recollection, is the evidence.
ZHOU_2004_ERRATA = {("Al", "A"): {"printed": 0.134873, "used": 0.314873}}

